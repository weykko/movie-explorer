package ru.urfu.movie_explorer.ui.screens.movies

/**
 * Причина ошибки при загрузке фильмов.
 * Используется для отображения соответствующего сообщения пользователю.
 */
enum class MoviesErrorReason {
    /** 5xx — сервер недоступен или сломан. */
    ServerUnavailable,

    /** 4xx — клиентская ошибка запроса (например, неверный фильтр). */
    RequestFailed,

    /** Сетевая ошибка / неизвестный сбой. Не специализировано — общее сообщение. */
    Network,
}
